#!/usr/bin/env python3
"""Start a new film from one of the examples.

    python tools/new_film.py <slug> --from albidhra|sky|light-speed|hiwar
Copies examples/<from>/ (sources only, no proj/ or out/) to films/<slug>/. Then edit script.json first, re-voice
(tools/voice/tts.py), and adapt the film/board/kinetic spec. See AGENTS.md §4.
--from hiwar (dialogue film): edit cast.json + scene.json, then bash build.sh (voices, lip sync, shot list, mix, build);
the generated voice / timeline / lip-sync files and the example's hand-made shots.json are not copied.
--lang en (default since 2026-10-24, owner decision: English script + English voices) recasts cast.json with English
edge-tts voices; --lang ar keeps the example's Arabic voices."""
import argparse, json, os, shutil, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EN_MALE = ["en-US-AndrewNeural", "en-US-BrianNeural", "en-GB-RyanNeural", "en-US-GuyNeural"]
EN_FEMALE = ["en-US-AvaNeural", "en-US-EmmaNeural", "en-GB-SoniaNeural", "en-US-JennyNeural"]
FEMALE_HINTS = ["Zariyah", "Salma", "Amany", "Fatima", "Laila", "Mouna", "Noura", "Rana", "Sana", "Iman", "Amina", "Reem",   # Arabic
                "Layla", "Aysha", "Amal", "Maryam", "Ava", "Emma", "Sonia", "Jenny", "Aria", "Ana", "Libby", "Maisie", "Michelle",
                "Natasha", "Clara", "Emily"]                                                                         # English

def main():
    ap = argparse.ArgumentParser(); ap.add_argument("slug"); ap.add_argument("--from", dest="src", default="albidhra",
                                                                              choices=["albidhra", "sky", "light-speed", "hiwar"])
    ap.add_argument("--keep-media", action="store_true", help="keep the example's voice/art (default: drop them)")
    ap.add_argument("--lang", choices=["en", "ar"], default="en", help="film language (default en: English script + voices)")
    a = ap.parse_args()
    dst = os.path.join(ROOT, "films", a.slug)
    if os.path.exists(dst): sys.exit(f"{dst} exists")
    ign = ["proj", "out", "__pycache__"] + ([] if a.keep_media else ["*.mp3", "tts.json"])
    if a.src == "hiwar":   # generated by tools/voice/dialogue.py; shots.json is anchored to the example's lines
        ign += ["timeline.json", "lipsync.json", "film_data.js", "shots.json"]
    shutil.copytree(os.path.join(ROOT, "examples", a.src), dst, ignore=shutil.ignore_patterns(*ign))
    print(f"created films/{a.slug} from examples/{a.src}")
    cp = os.path.join(dst, "cast.json")
    if a.lang == "en" and os.path.exists(cp):          # English voices: distinct per character (gender from the old voice)
        C = json.load(open(cp, encoding="utf-8")); male = iter(EN_MALE); female = iter(EN_FEMALE)
        for cid, ch in C["characters"].items():
            v = ch.setdefault("voice", {})
            if v.get("provider", "edge") == "edge":
                v["voice"] = next(female if any(k in v.get("voice", "") for k in FEMALE_HINTS) else male)
                v["rate"], v["pitch"] = "+0%", "+0Hz"
        json.dump(C, open(cp, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        print("cast.json recast with English voices:", {k: c["voice"].get("voice") for k, c in C["characters"].items()})
    if a.lang == "en":
        print("write the script in ENGLISH (scene.json / script.json); titles in a Latin font (assets/fonts: Caveat, ArefRuqaa-latin)")
    if a.src == "hiwar":
        print("next: edit cast.json + scene.json -> bash build.sh -> look at the sheet (tools/render/snap.py) -> shots.json by hand"
              " -> film.js acting (see skills/talking-characters)")
    else:
        print("next: edit script.json -> python tools/voice/tts.py script.json (run inside the film folder) -> adapt -> build.sh")

if __name__ == "__main__":
    main()
